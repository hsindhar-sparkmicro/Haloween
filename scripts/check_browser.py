import argparse
import json
from pathlib import Path
from playwright.sync_api import sync_playwright

parser=argparse.ArgumentParser()
parser.add_argument('--url',default='http://127.0.0.1:8080')
parser.add_argument('--cdp')
parser.add_argument('--request-url')
parser.add_argument('--output-directory',default='validation')
args=parser.parse_args()
output=Path(args.output_directory)
root=output/'screenshots'; root.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.connect_over_cdp(args.cdp) if args.cdp else p.chromium.launch()
    context=browser.new_context()
    page=context.new_page()
    errors=[]
    page.on('pageerror',lambda error: errors.append(str(error)))
    reports=[]
    for width,height in [(800,480),(1280,720),(1920,1080)]:
        page.set_viewport_size({'width':width,'height':height})
        page.goto(args.url); page.wait_for_function("() => document.querySelector('#connection').textContent.includes('Connected')")
        for screen in ['dashboard','haunt','party','detector']:
            page.keyboard.press('Escape')
            page.locator(f'[data-screen="{screen}"]').click()
            page.wait_for_timeout(150)
            report=page.evaluate('''() => {const screen=document.querySelector('.screen.active'); const main=document.querySelector('main').getBoundingClientRect(); return {screen:screen.id, scroll:screen.scrollHeight>screen.clientHeight+2, controls:[...screen.querySelectorAll('button,input,select,a')].filter(e=>e.getBoundingClientRect().height>0).map(e=>{const r=e.getBoundingClientRect();return {label:e.getAttribute('aria-label')||e.textContent.trim(),width:r.width,height:r.height,visible:r.top>=main.top&&r.bottom<=main.bottom+1&&r.left>=0&&r.right<=innerWidth}})}}''')
            report.update(width=width,height=height)
            reports.append(report)
            page.screenshot(path=str(root/f'{screen}-{width}x{height}.png'))
        page.locator('[data-open="settings-dialog"]').last.click()
        page.locator('#setting-units').select_option('F')
        page.locator('#save-settings').click()
        page.wait_for_timeout(1100)
        assert page.evaluate('document.querySelector("#scan-temperature").textContent.endsWith("F")')
    page.keyboard.press('Escape')
    page.locator('[data-screen="dashboard"]').click()
    assert page.locator('#dashboard .tile,#candy-value,#add-candy').count()==0
    page.keyboard.press('Escape')
    page.locator('[data-screen="haunt"]').click(); page.locator('#activate-haunt').click()
    page.wait_for_function('() => document.querySelector("#activate-haunt").disabled')
    page.locator('#scene-back').click(); page.wait_for_function('() => !document.querySelector("#activate-haunt").disabled')
    page.keyboard.press('Escape')
    page.locator('[data-screen="detector"]').click(); page.locator('#scan-toggle').click()
    page.wait_for_function('() => document.querySelector("#scan-toggle").textContent==="Stop scan"')
    page.wait_for_timeout(1500); page.locator('#scan-toggle').click()
    page.keyboard.press('Escape')
    page.locator('[data-screen="party"]').click(); page.locator('[data-open="tasks-dialog"]').click()
    page.locator('[data-record-form="task"] input').fill('Browser test task')
    page.locator('[data-record-form="task"] button').click()
    page.locator('#task-list .record-row').filter(has_text='Browser test task').wait_for()
    page.locator('#task-list .record-row').filter(has_text='Browser test task').locator('input').check()
    page.wait_for_timeout(300)
    page.locator('#task-list .record-row').filter(has_text='Browser test task').get_by_role('button',name='Delete Browser test task').click()
    page.locator('#tasks-dialog [data-close]').click()
    page.locator('[data-open="music-dialog"]').click()
    page.locator('#music-upload').set_input_files({'name':'midnight.wav','mimeType':'audio/wav','buffer':Path('halloween_hub/static/assets/midnight.wav').read_bytes()})
    page.locator('#track-list .track-row').filter(has_text='midnight.wav').wait_for()
    page.locator('#track-list .track-row').filter(has_text='midnight.wav').get_by_role('button',name='Play',exact=True).click()
    page.wait_for_function('() => !document.querySelector("#music-player").paused')
    page.wait_for_timeout(1000)
    audio=page.evaluate('({time:document.querySelector("#music-player").currentTime,muted:document.querySelector("#music-player").muted})')
    page.locator('#track-list .track-row').filter(has_text='midnight.wav').get_by_role('button',name='Delete midnight.wav').click()
    page.locator('#music-dialog [data-close]').click()
    page.request.patch((args.request_url or args.url)+'/api/settings',data={'units':'C'})
    (output/'browser-report.json').write_text(json.dumps({'reports':reports,'errors':errors,'audio':audio},indent=2))
    print(json.dumps({'errors':errors,'audio':audio,'overflow':[{'screen':r['screen'],'size':f"{r['width']}x{r['height']}",'hidden':[c['label'] for c in r['controls'] if not c['visible']]} for r in reports if r['scroll'] or any(not c['visible'] for c in r['controls'])]},indent=2))
    assert not errors, errors
    assert all(not r['scroll'] and all(c['visible'] and c['width'] >= 47.9 and c['height'] >= 47.9 for c in r['controls']) for r in reports), 'Layout or touch-target regression; see validation/browser-report.json'
    context.close()
    if not args.cdp: browser.close()
